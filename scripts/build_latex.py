"""Render the report's shared content to native LaTeX with editable equations."""
from pathlib import Path
from html.parser import HTMLParser
import json,shutil
ROOT=Path(__file__).resolve().parents[1]
REPORT=ROOT/'report'
EVENTS=json.loads((REPORT/'content.json').read_text())

def escape(text):
    replacements={'\\':r'\textbackslash{}','&':r'\&','%':r'\%','$':r'\$','#':r'\#',
                  '_':r'\_','{':r'\{','}':r'\}','~':r'\textasciitilde{}','^':r'\textasciicircum{}'}
    text=text.replace('\u2019',"'").replace('\u2013','--').replace('\u2014','---').replace('\u00a0',' ')
    return ''.join(replacements.get(c,c) for c in text)

class Inline(HTMLParser):
    def __init__(self): super().__init__(convert_charrefs=True); self.parts=[]; self.tags=[]
    def handle_starttag(self,tag,attrs):
        if tag=='br': self.parts.append(r'\\'); return
        mapping={'b':r'\textbf{','i':r'\textit{','sub':r'\textsubscript{','super':r'\textsuperscript{'}
        if tag=='link':
            self.parts.append(r'\newline\url{'); self.tags.append(tag)
        elif tag in mapping: self.parts.append(mapping[tag]); self.tags.append(tag)
    def handle_endtag(self,tag):
        if tag in self.tags: self.parts.append('}'); self.tags.remove(tag)
    def handle_data(self,data): self.parts.append(data if 'link' in self.tags else escape(data))
def inline(value):
    parser=Inline(); parser.feed(str(value)); return ''.join(parser.parts)

header=r'''% Generated by scripts/build_latex.py from report/content.json.
% Statistical values come from results/ and the executed analysis notebook.
\documentclass[11pt,a4paper]{article}
\usepackage[T1]{fontenc}
\usepackage[utf8]{inputenc}
\usepackage{mathptmx,amsmath,amssymb}
\usepackage[left=2cm,right=2cm,top=1.6cm,bottom=1.65cm]{geometry}
\usepackage{graphicx,booktabs,tabularx,array}
\usepackage[table]{xcolor}
\usepackage[colorlinks=true,urlcolor=blue,linkcolor=black]{hyperref}
\graphicspath{{images/}}
\setlength{\parindent}{0pt}
\setlength{\parskip}{5.5pt}
\setlength{\tabcolsep}{4pt}
\renewcommand{\arraystretch}{1.12}
\urlstyle{same}
\hypersetup{pdftitle={Forecasting Kazakhstan's Total Monthly Electricity Generation Using SARIMA},pdfauthor={Mathematics project group, Nazarbayev University}}
\begin{document}
\fontsize{10.5}{13.5}\selectfont
'''
pieces=[header]
images=REPORT/'images'; images.mkdir(exist_ok=True)
for event in EVENTS:
    kind=event['type']
    if kind=='pagebreak': pieces.append(r'\clearpage'+'\n'); continue
    if kind=='figure':
        filename=event['filename']; shutil.copy2(ROOT/'figures'/filename,images/filename)
        pieces.append(r'\begin{center}\includegraphics[width=\linewidth,height='+f'{event["height_cm"]:.2f}'+r'cm,keepaspectratio]{'+filename+r'}\end{center}'+'\n')
        continue
    if kind=='table':
        rows=event['rows']; n=len(rows[0]); widths=event.get('widths')
        weights=[n*w/sum(widths) for w in widths] if widths else [1.0]*n
        cols=''.join(r'>{\hsize='+f'{w:.5f}'+r'\hsize\linewidth=\hsize\raggedright\arraybackslash}X' for w in weights)
        pieces.append(r'{\fontsize{9.2}{11.3}\selectfont\begin{tabularx}{\linewidth}{@{}'+cols+r'@{}}\toprule'+'\n')
        for i,row in enumerate(rows):
            if i==0: pieces.append(r'\rowcolor[gray]{0.94}'+'\n')
            pieces.append(' & '.join(inline(cell) for cell in row)+r' \\'+'\n')
            if i==0: pieces.append(r'\midrule'+'\n')
        pieces.append(r'\bottomrule\end{tabularx}}\par'+'\n')
        continue
    text=event['text']; style=event['style']; content=inline(text)
    if style=='ReportTitle':
        pieces.append(r'\begin{center}{\bfseries\fontsize{18}{21}\selectfont '+content+r'}\end{center}'+'\n')
    elif style=='ReportMeta': pieces.append(r'\begin{center}{\fontsize{10}{13}\selectfont '+content+r'}\end{center}'+'\n')
    elif style=='SectionAcademic': pieces.append(r'\par\vspace{5pt}{\bfseries\fontsize{12.5}{16}\selectfont '+content+r'}\par\vspace{2pt}'+'\n')
    elif style=='SubAcademic': pieces.append(r'\par{\bfseries '+content+r'}\par'+'\n')
    elif style=='EquationAcademic':
        equation=(r'\widehat{y}_{T+h\mid T}=y_{T+h-12}\tag{1}' if '(1)' in text
                  else r'z_t=c+\phi z_{t-1}+\varepsilon_t+\theta\varepsilon_{t-12}\tag{2}')
        pieces.append(r'\['+equation+r'\]'+'\n')
    elif style in ['CaptionAcademic','SmallAcademic']:
        pieces.append(r'{\fontsize{9}{11.3}\selectfont '+content+r'\par}'+'\n')
    else: pieces.append(content+r'\par'+'\n')
pieces.append(r'\end{document}'+'\n')
(REPORT/'main.tex').write_text('\n'.join(pieces))
print('Wrote report/main.tex and copied its four figure assets.')
